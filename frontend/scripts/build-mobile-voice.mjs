import { build } from 'vite';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const result = await build({
  configFile: false,
  root: fileURLToPath(root),
  build: {
    lib: {
      entry: fileURLToPath(new URL('src/lib/voice/mobileVoiceCube.ts', root)),
      formats: ['iife'],
      name: 'MobileVoiceCube',
    },
    target: 'es2020',
    minify: true,
    write: false,
  },
});
const outputBundle = Array.isArray(result) ? result[0] : result;
const code = outputBundle.output.find((item) => item.type === 'chunk').code;
const html = `<!doctype html>
<!-- Generated by npm run build:mobile-voice; shared with the desktop VoiceCubeStage. -->
<html><head><meta name="viewport" content="width=device-width,initial-scale=1,user-scalable=no">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'">
<style>html,body{margin:0;width:100%;height:100%;overflow:hidden;background:transparent}canvas{position:absolute;top:0;left:50%;transform:translateX(-50%);width:100%;max-width:260px;height:112px}</style></head>
<body><canvas aria-hidden="true"></canvas><script>${code}</script></body></html>\n`;
const output = new URL(
  '../../packages/SuzentCore/Sources/SuzentCore/Resources/voice-cube.html',
  import.meta.url
);
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== html)
    throw new Error('Run npm run build:mobile-voice to sync the mobile voice animation.');
} else {
  await writeFile(output, html);
}
