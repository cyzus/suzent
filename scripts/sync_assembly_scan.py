"""Generate native scan layers from config/assembly_scan.json; use --check in CI."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    layers = json.loads(
        (ROOT / "config/assembly_scan.json").read_text(encoding="utf-8")
    )
    swift = "// Generated by scripts/sync_assembly_scan.py. Do not edit.\n"
    swift += "enum AssemblyScan {\n"
    kotlin = "// Generated by scripts/sync_assembly_scan.py. Do not edit.\n"
    kotlin += "package com.suzent.mobile\n\n"
    kotlin += "internal data class ScanLayer(val color: Long, val opacity: Double, val width: Double)\n"
    kotlin += "internal object AssemblyScan {\n"
    for side, values in layers.items():
        swift += f"    static let {side}: [(color: UInt32, opacity: Double, width: Double)] = [\n"
        kotlin += f"    val {side} = listOf(\n"
        for layer in values:
            color, opacity, width = layer["color"], layer["opacity"], layer["width"]
            swift += f"        (0x{color}, {opacity}, {width}),\n"
            kotlin += f"        ScanLayer(0xFF{color}, {opacity}, {width}),\n"
        swift += "    ]\n"
        kotlin += "    )\n"
    outputs = {
        "packages/SuzentCore/Sources/SuzentCore/AssemblyScan.swift": swift + "}\n",
        "apps/android/app/src/main/java/com/suzent/mobile/AssemblyScan.kt": kotlin
        + "}\n",
    }
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale generated scan layers: {name}")
        else:
            path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
